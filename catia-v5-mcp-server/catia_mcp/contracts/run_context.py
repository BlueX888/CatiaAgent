"""Host-owned run identity for correlation, never a model permission token.

``RunContext`` is generated by the host and is not exposed as a tool argument.
It links a platform session/turn to a CATIA operation id, the source snapshot,
code/contract versions and an optional deadline.  ``RunRecord`` adds the
persistence fields (state source and a monotonic sequence) used by a sidecar
store; the coordinator and journal remain the execution truth.
"""

from __future__ import annotations

from typing import Literal, Optional

from pydantic import Field

from .base import CanonicalModel, WireInt, WireModel

RUN_CONTEXT_SCHEMA = "catia-run-context/1"
_HEX64 = r"^[a-f0-9]{64}$"


class RunContext(WireModel):
    draft_schema: Literal["catia-run-context/1"] = Field(alias="schema")
    runId: str = Field(min_length=1, max_length=128)
    attemptId: str = Field(min_length=1, max_length=128)
    sourceFingerprint: str = Field(pattern=_HEX64)
    codeVersion: str = Field(min_length=1, max_length=128)
    contractVersion: str = Field(min_length=1, max_length=128)
    modelId: Optional[str] = Field(default=None, max_length=256)
    promptId: Optional[str] = Field(default=None, max_length=256)
    workingDirectory: str = Field(min_length=1, max_length=4096)
    sessionId: Optional[str] = Field(default=None, max_length=128)
    operationId: Optional[str] = Field(default=None, max_length=128)
    deadlineMs: Optional[WireInt] = Field(default=None, ge=0)
    createdAt: str = Field(min_length=1, max_length=64)


class RunRecord(CanonicalModel):
    context: RunContext
    stateSource: Literal["host", "coordinator", "journal"]
    sequence: WireInt = Field(ge=0)
    updatedAt: str = Field(min_length=1, max_length=64)
